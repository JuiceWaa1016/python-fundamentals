#concatenation of strings Lesson

first_name = "Joshua"
Last_name = "Flora"
age = 23

#plus operator
print(first_name + " " + Last_name + " is " + str(age) + " years old.")

#F-Strings
print(f"{first_name} {Last_name} is {age} years old.")

#join method
print(" ".join([first_name, Last_name, "is", str(age), "years old."]))
